"""Layer B (part 1) — JOURNAL.md + EVIDENCE.md -> structured facts.

The journal is the single source of truth for *facts* (numbers). A presentation
is generated by an LLM from a story-prompt; to keep "LLM writes the narrative"
safe, every number it emits must trace back to a number the journal actually
states. This module turns the journal into:

  journal_numbers()   -> the canonical *bag of numbers* the journal asserts
                         (the allow-list the gate checks generated prose against)
  structured_facts()  -> a curated dict of stable-keyed headline facts
                         (RE-15.neighbors_delta, C1.fp8_gap_owt, ...), each value
                         re-extracted live from the journal so keys are durable
                         but values never go stale

`gate.py` consumes `journal_numbers()`. The build prompt is fed
`structured_facts()` so the LLM cites named facts, not free-floating digits.
"""
import importlib
import os
import re
import sys
from decimal import Decimal, InvalidOperation, ROUND_HALF_EVEN

from smh.config import resolve_root
ROOT = resolve_root(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, ROOT)

# A numeric token: optional sign, digits, optional decimals. Captures the run of
# digits exactly as written (so 3.7818 and 3.782 are distinct tokens).
NUM_RE = re.compile(r"(?<![\w.])([-+]?\d+(?:\.\d+)?)(?![\w])")


def _default_catalog(root=None):
    """The default project's `FactsCatalog`, resolved through
    `config.catalog_ref(root, "facts_catalog")` (`[projects.<default>]`, or a
    solo repo's top-level key). A default project that registers no facts
    catalog gets `null_catalog` — an EMPTY named-fact map over its own ledger
    files, so the gate's number bag is still the project's journal and nothing
    is borrowed from another project. The zero-arg call (gate/build/propose)
    resolves against the repo root."""
    from smh import config
    root = root or ROOT
    ref = config.catalog_ref(root, "facts_catalog")
    if ref:
        return config.instantiate(ref)
    return null_catalog(config.repo_default_project(root), root)


def null_catalog(project, root=None):
    """A `FactsCatalog` with NO named facts whose `journal_text` is `project`'s
    own ledger — what a project that registers no `facts_catalog` gets, so its
    gate still sees its numbers but a deck has no named facts to cite. Logs one
    line: silent substitution is how the 2026-11 audit found LDP's facts being
    reported for other projects."""
    from smh import journal_xref as jx
    from smh.adapters.facts import RegexFactsCatalog
    root = root or ROOT
    files = jx.ledger_files(project, root) or ()
    print(f"[facts] project {project!r} registers no facts_catalog — "
          f"empty named-fact catalog over {list(files) or 'NO ledger files'}",
          file=sys.stderr)
    return RegexFactsCatalog(ledger_paths=[os.path.join(root, f) for f in files],
                             facts={})


def _text():
    return _default_catalog().journal_text()


# --- the canonical numeric comparator (shared by gate.py; reused by the planned
# repro-check). Decimal, not float: exact at the token's written precision, no
# binary-float artifacts (round(2.675,2)==2.67 but 2.675 quantizes to 2.68), and
# sign-aware by construction (a flipped delta does not match its positive twin).
def to_decimal(tok):
    """A numeric token (str or number) -> Decimal preserving sign and written
    precision, or None if non-numeric. Tolerates thousands commas, a trailing %,
    and a trailing period (sentence punctuation)."""
    if isinstance(tok, Decimal):
        return tok
    s = str(tok).strip().rstrip(".").replace(",", "")
    if s.endswith("%"):
        s = s[:-1]
    try:
        return Decimal(s)
    except InvalidOperation:
        return None


def _decimals(d):
    exp = d.as_tuple().exponent
    return -exp if isinstance(exp, int) and exp < 0 else 0


def number_matches(token, value):
    """True iff generated `token` equals journal `value` at the token's stated
    precision. Decimal-exact (so '3.787' matches 3.7874) and sign-aware (so
    '-0.024' does NOT match +0.024). Replaces the old `round(value, dec) == g`
    float compare; same half-even rounding, fewer artifacts."""
    d = to_decimal(token)
    v = to_decimal(value)
    if d is None or v is None:
        return False
    q = Decimal(1).scaleb(-_decimals(d))
    return v.quantize(q, rounding=ROUND_HALF_EVEN) == d


def journal_numbers(text=None):
    """All distinct numeric tokens the journal states, as floats. This is the
    allow-list: a generated number is legitimate iff it (or a rounding of it)
    is in here."""
    text = text if text is not None else _text()
    nums = set()
    for m in NUM_RE.finditer(text):
        try:
            nums.add(float(m.group(1)))
        except ValueError:
            pass
    return nums


def all_project_numbers(root=None):
    """Union of `journal_numbers` over EVERY co-located project segment (T4a) —
    the allow-list a CROSS-PROJECT render gates against. A single-project deck
    keeps `journal_numbers()` (LDP-scoped, byte-unchanged); the meta-workflow deck
    spans all three ledgers (LDP + FracBits + BitDistiller), so a number it cites
    is legitimate iff some project's segment asserts it. Reuses the same loader the
    graph view uses, so the gate's notion of "the journal" matches the graph's."""
    from smh import journal_xref as jx
    nums = set()
    for _project, text in jx.load_segments(root):
        nums |= journal_numbers(text)
    return nums


def structured_facts(text=None, catalog=None):
    """Curated stable-keyed facts, values extracted live from the journal.
    Missing keys (journal prose changed) surface as None so the build can warn.

    The catalog (default = LDP's `LdpFactsCatalog`) owns the
    `{key: (regex, group, cast)}` map and the ledger files; this is the core entry
    point the build prompt and repro-check call. Pass `text` to resolve the map
    against a specific journal snapshot instead of the catalog's live ledger."""
    catalog = catalog if catalog is not None else _default_catalog()
    if text is None:
        return catalog.named_facts()
    return catalog.resolve(text)


if __name__ == "__main__":
    import json
    facts = structured_facts()
    nums = journal_numbers()
    missing = [k for k, v in facts.items() if v is None]
    print(f"journal_numbers: {len(nums)} distinct tokens")
    print(f"structured_facts: {len(facts) - len(missing)}/{len(facts)} resolved")
    if missing:
        print("  UNRESOLVED (regex drifted from journal):", missing)
    print(json.dumps({k: v for k, v in facts.items() if v is not None}, indent=1))
